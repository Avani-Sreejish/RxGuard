const DICTS: Record<Lang, Dict> = { en, ml, hi };

export const LANGS: { code: Lang; label: string; name: string }[] = [
  { code: "en", label: "EN", name: "English" },
  { code: "ml", label: "മല", name: "മലയാളം" },
  { code: "hi", label: "हि", name: "हिन्दी" },
];

export type T = (key: string, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  return (key, vars) => {
    let s = DICTS[lang][key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

export const LangContext = createContext<{ lang: Lang; t: T; setLang: (l: Lang) => void }>({
  lang: "en",
  t: makeT("en"),
  setLang: () => {},
});

export const useI18n = () => useContext(LangContext);

/** Severity in the reader's language; English severity word for template claims stays the database's own. */
export function sevLabel(t: T, sev: string) {
  return t(`sev.${sev}`);
}

/** The database fact for a finding, in the reader's language (drug names stay as recorded). */
export function dbClaim(t: T, lang: Lang, f: { drug_a: string; drug_b: string; severity: string }) {
  if (f.severity === "Unknown") return t("claim.dbUnknown", { a: f.drug_a, b: f.drug_b });
  return t("claim.db", { a: f.drug_a, b: f.drug_b, sev: lang === "en" ? f.severity : t(`sev.${f.severity}`) });
}

/** Known fixed sentences from the backend, mapped to their translation keys. */
export function fixedSentenceKey(text: string): string | null {
  if (text.startsWith("Insufficient evidence retrieved")) return "insufficient";
  if (text.startsWith("RxGuard does not provide dosing")) return "banner.DOSING";
  return null;
}
